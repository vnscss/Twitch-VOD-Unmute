/*
 * Shared background logic for Twitch VOD Unmute.
 *
 * Platform-specific files provide the WebExtension API object and any redirection
 * adapter. Firefox uses a blocking webRequest listener; Chrome MV3 uses
 * declarativeNetRequest rules generated from the same probe results.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.TVUBackgroundCore = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  const SETTINGS_KEYS = Object.keys(globalThis.TVUCore.DEFAULT_SETTINGS);
  const PROBE_TTL_MS = 10 * 60 * 1000;
  // Twitch's CDN can be slow; a 2.5s abort made otherwise-available segments
  // look purged. Keep these values in sync with the literals in pageProbe().
  const PROBE_ATTEMPTS = 2;
  const PROBE_TIMEOUT_MS = 6000;
  const PROBE_CONCURRENCY = 12;
  const PROBE_CACHE_LIMIT = 2000;
  const SEEN_TTL_MS = 10 * 1000;
  const QUALITY_TTL_MS = 10 * 60 * 1000;
  // A live stream must never enter this path, so a long wait is only ever
  // applied to an active VOD scan. It covers one full probe chain plus queueing.
  const PENDING_TIMEOUT_MS = 30000;
  // Hard ceiling for a single scan. Cancelling releases every waiting player
  // request instead of letting a stalled CDN hold segments indefinitely.
  const SCAN_TIMEOUT_MS = 60000;
  // Two name shapes across the seven possible qualities. These are safety
  // ceilings, not the normal path: exact DVR names usually need one probe.
  const MAX_PROBES_PER_SEGMENT = 14;
  const MAX_PROBES_PER_SCAN = 3000;
  const CHECKED_SEGMENT_LIMIT = 2000;

  function createBackground(options) {
    const settings = options || {};
    const api = settings.api;
    const Core = settings.Core || globalThis.TVUCore;
    const platform = settings.platform || {};

    if (!api || !Core) throw new Error('createBackground requires api and Core');

    const useBlocking = platform.useBlocking !== false;
    const emitRedirect = typeof platform.emitRedirect === 'function'
      ? platform.emitRedirect
      : async function () {};
    const removeTabRules = typeof platform.removeTabRules === 'function'
      ? platform.removeTabRules
      : async function () {};
    const clearAllRules = typeof platform.clearAllRules === 'function'
      ? platform.clearAllRules
      : async function () {};

    let redirectCache = null;
    let cacheLoaded = false;

    // Requests generated by this extension must not be mistaken for new player
    // requests, and probes must not wait for the scan that started them.
    const internalUrls = new Set();
    const probeUrls = new Set();
    const seenMasterPlaylists = new Map();
    const seenMutedPlaylists = new Map();
    const pendingBySegment = new Map();
    const checkedSegments = new Set();
    // A scan is registered as soon as a VOD playlist is observed, before any
    // asynchronous read starts. The blocking listener uses this to distinguish
    // a VOD that is being repaired from a live stream that must be untouched.
    const activeScans = new Map();
    const probeKeysByTab = new Map();
    const pageUrlsByTab = new Map();
    let nextScanId = 1;

    /* ---------------------------------------------------------------- */
    /* Small helpers                                                     */
    /* ---------------------------------------------------------------- */

    class ScanCancelledError extends Error {
      constructor() {
        super('scan cancelled');
        this.name = 'ScanCancelledError';
      }
    }

    function pathnameOf(url) {
      try {
        return new URL(url).pathname;
      } catch (_) {
        return String(url).split('?')[0].split('#')[0];
      }
    }

    function pathPrefix(url) {
      return pathnameOf(url).replace(/[^/]*$/, '');
    }

    function assertActive(signal) {
      if (signal && signal.aborted) throw new ScanCancelledError();
    }

    function isCancellation(error) {
      return Boolean(error) && error.name === 'ScanCancelledError';
    }

    function playlistIdentity(url) {
      return Core.playlistKey ? Core.playlistKey(url) : pathnameOf(url);
    }

    function scanKey(tabId, url) {
      return tabId + '|' + playlistIdentity(url);
    }

    function isMutedSegmentUrl(url) {
      const pathname = pathnameOf(url);
      // Only muted segments can need a redirect. Waiting on ordinary segments
      // would add latency to every request and can trigger Twitch's #2000 error.
      return /(?:^|\/)\d+-muted\.(?:ts|mp4)$/i.test(pathname);
    }

    // The player can append query parameters/tokens to a segment request. Match
    // redirects by origin + pathname so the mapping survives those differences.
    function segmentKey(url) {
      try {
        const parsed = new URL(url);
        return parsed.origin + parsed.pathname;
      } catch (_) {
        return String(url).split('?')[0].split('#')[0];
      }
    }

    function isRecent(map, url) {
      const at = map.get(url);
      return typeof at === 'number' && Date.now() - at < SEEN_TTL_MS;
    }

    function noteSeen(map, url) {
      map.set(url, Date.now());
      for (const [key, at] of map) {
        if (Date.now() - at >= SEEN_TTL_MS) map.delete(key);
      }
    }

    function pendingFor(url) {
      let entry = pendingBySegment.get(url);
      if (!entry) {
        let resolve;
        const promise = new Promise(done => { resolve = done; });
        entry = { promise, resolve };
        pendingBySegment.set(url, entry);
      }
      return entry;
    }

    function markSegmentChecked(url) {
      checkedSegments.add(url);
      if (checkedSegments.size > CHECKED_SEGMENT_LIMIT) {
        const oldest = checkedSegments.values().next().value;
        checkedSegments.delete(oldest);
      }

      const entry = pendingBySegment.get(url);
      if (entry) {
        entry.resolve();
        pendingBySegment.delete(url);
      }
    }

    async function waitForSegment(url) {
      if (checkedSegments.has(url)) return;

      const entry = pendingFor(url);
      let timer;
      try {
        await Promise.race([
          entry.promise,
          new Promise(done => { timer = setTimeout(done, PENDING_TIMEOUT_MS); })
        ]);
      } finally {
        clearTimeout(timer);
        pendingBySegment.delete(url);
      }
    }

    // If a scan fails or is cancelled, do not leave player requests hanging.
    function releasePlaylistSegments(playlistUrl) {
      const prefix = pathPrefix(playlistUrl);
      for (const url of Array.from(pendingBySegment.keys())) {
        if (pathnameOf(url).startsWith(prefix) && isMutedSegmentUrl(url)) {
          markSegmentChecked(url);
        }
      }
    }

    function activeScanFor(tabId, url) {
      const pathname = pathnameOf(url);
      for (const token of activeScans.values()) {
        if (token.tabId === tabId && pathname.startsWith(token.prefix)) return token;
      }
      return null;
    }

    function activeScanCount(tabId) {
      let count = 0;
      for (const token of activeScans.values()) {
        if (token.tabId === tabId) count++;
      }
      return count;
    }

    function beginScan(tabId, url) {
      const key = scanKey(tabId, url);
      if (activeScans.has(key)) return null;

      const token = {
        id: nextScanId++,
        key,
        tabId,
        url,
        prefix: pathPrefix(url),
        controller: new AbortController(),
        timer: null,
        probeKeys: new Set(),
        diagnostics: {
          dvrRequests: 0,
          dvrStatus: 'not_requested',
          dvrNames: 0,
          failedProbes: 0,
          requests: 0,
          waitedSegments: 0
        }
      };
      token.timer = setTimeout(() => {
        console.warn('[tvu] scan timed out for tab', tabId);
        token.controller.abort();
        releasePlaylistSegments(url);
      }, SCAN_TIMEOUT_MS);
      activeScans.set(key, token);
      return token;
    }

    function endScan(token) {
      if (!token) return;
      clearTimeout(token.timer);
      if (activeScans.get(token.key) === token) activeScans.delete(token.key);
      releasePlaylistSegments(token.url);
    }

    function cancelTabScans(tabId) {
      for (const token of Array.from(activeScans.values())) {
        if (token.tabId !== tabId) continue;
        token.controller.abort();
        if (activeScans.get(token.key) === token) activeScans.delete(token.key);
        clearTimeout(token.timer);
        releasePlaylistSegments(token.url);
      }
    }

    function cancelAllScans() {
      for (const token of Array.from(activeScans.values())) {
        token.controller.abort();
        if (activeScans.get(token.key) === token) activeScans.delete(token.key);
        clearTimeout(token.timer);
        releasePlaylistSegments(token.url);
      }
    }

    /* ---------------------------------------------------------------- */
    /* Session storage helpers                                           */
    /* ---------------------------------------------------------------- */

    async function sessionGet(key, fallback) {
      try {
        const values = await api.storage.session.get(key);
        return Object.prototype.hasOwnProperty.call(values, key) ? values[key] : fallback;
      } catch (error) {
        console.warn('[tvu] session read failed', error);
        return fallback;
      }
    }

    async function sessionSet(key, value) {
      try {
        await api.storage.session.set({ [key]: value });
      } catch (error) {
        console.warn('[tvu] session write failed', error);
      }
    }

    // Page context is needed to tell a VOD playlist from a live playlist when
    // the CDN URL has no VOD marker. Persist it so a Chrome service-worker
    // restart does not lose the classification.
    async function setPageUrl(tabId, url) {
      pageUrlsByTab.set(tabId, url);
      const pages = await sessionGet('pageUrls', {});
      pages[tabId] = url;
      await sessionSet('pageUrls', pages);
    }

    async function getPageUrl(tabId) {
      if (pageUrlsByTab.has(tabId)) return pageUrlsByTab.get(tabId);
      const pages = await sessionGet('pageUrls', {});
      return pages[tabId] || null;
    }

    async function forgetPageUrl(tabId) {
      pageUrlsByTab.delete(tabId);
      const pages = await sessionGet('pageUrls', {});
      delete pages[tabId];
      await sessionSet('pageUrls', pages);
    }

    async function seedPageUrls() {
      if (!api.tabs || !api.tabs.query) return;
      try {
        const tabs = await api.tabs.query({});
        const pages = await sessionGet('pageUrls', {});
        for (const tab of tabs || []) {
          if (tab && tab.id != null && tab.url && /^https?:\/\//i.test(tab.url)) {
            pageUrlsByTab.set(tab.id, tab.url);
            pages[tab.id] = tab.url;
            if (Core.isVodPageUrl(tab.url)) {
              const vodId = Core.vodIdFromUrl(tab.url);
              await recordDiagnostics(tab.id, {
                mode: 'vod',
                reason: 'VOD page',
                url: tab.url,
                vodId: vodId || undefined
              });
            }
          }
        }
        await sessionSet('pageUrls', pages);
      } catch (error) {
        console.warn('[tvu] could not seed page URLs', error && error.message);
      }
    }

    async function recordDiagnostics(tabId, patch) {
      const key = 'diagnostics:' + tabId;
      const current = (await sessionGet(key, null)) || {};
      await sessionSet(key, Object.assign({}, current, patch, {
        tabId,
        activeScan: activeScanCount(tabId) > 0,
        at: Date.now()
      }));
    }

    async function getRedirects() {
      if (!cacheLoaded) {
        redirectCache = await sessionGet('redirects', {});
        cacheLoaded = true;
      }
      return redirectCache || {};
    }

    async function putRedirects(map) {
      redirectCache = map;
      cacheLoaded = true;
      await sessionSet('redirects', map);
    }

    api.storage.onChanged.addListener((changes, area) => {
      if (area === 'session' && changes.redirects && cacheLoaded) {
        redirectCache = changes.redirects.newValue || {};
      }
    });

    async function getSettings() {
      const values = await api.storage.sync.get(SETTINGS_KEYS);
      return Core.normaliseSettings(values);
    }

    api.runtime.onInstalled.addListener(async () => {
      await api.storage.sync.set(await getSettings());
      await putRedirects({});
      await sessionSet('probes', {});
      await sessionSet('stats', {});
      await sessionSet('tabUrls', {});
      await sessionSet('pageUrls', {});
      await clearAllRules();
    });

    /* ---------------------------------------------------------------- */
    /* Page-context helpers                                              */
    /*                                                                   */
    /* These functions are injected into the twitch.tv tab. Twitch's CDN  */
    /* rejects requests coming from an extension origin, so all playlist  */
    /* reads and segment probes happen in the page's own context.         */
    /* ---------------------------------------------------------------- */

    async function pageFetch(url) {
      // Playlist/DVR reads also need a ceiling: a stalled CDN request must not
      // keep the scan (and therefore VOD segment requests) alive forever.
      // Keep this literal in sync with PLAYLIST_TIMEOUT_MS if it is configurable.
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), 8000);
      try {
        const response = await fetch(url, { signal: controller.signal });
        const text = await response.text();
        return { ok: response.ok, status: response.status, text };
      } catch (error) {
        return { ok: false, status: 0, text: '', error: String(error && error.message || error) };
      } finally {
        clearTimeout(timer);
      }
    }

    async function pageProbe(url) {
      let response = null;
      let errors = 0;

      // Keep these literals in sync with PROBE_ATTEMPTS/PROBE_TIMEOUT_MS: this
      // function is serialised into the page and cannot see background constants.
      for (let attempt = 0; attempt < 2; attempt++) {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 6000);
        try {
          // Only ask for Range. Extra headers such as Cache-Control/Pragma can
          // trigger a CDN preflight that Twitch rejects with 403.
          response = await fetch(url, {
            headers: { Range: 'bytes=0-1' },
            signal: controller.signal
          });
          clearTimeout(timer);
          break;
        } catch (_) {
          errors++;
        }
        clearTimeout(timer);
      }

      if (!response) return { errors };

      const result = {
        status: response.status,
        errors,
        lastModified: response.headers.get('last-modified')
      };
      try {
        if (response.body && response.body.cancel) await response.body.cancel();
      } catch (_) {
        /* nothing to do */
      }
      return result;
    }

    function paintSeekbar(bands, colours, currentQuality) {
      const state = window.__tvuSeekbar || (window.__tvuSeekbar = {
        generation: 0,
        observer: null,
        scheduled: false
      });

      state.bands = Array.isArray(bands) ? bands : [];
      state.colours = colours || {};
      state.quality = currentQuality;
      state.generation++;
      const generation = state.generation;

      const draw = () => {
        const root = document.querySelector('div.seekbar-bar');
        if (!root || !root.firstElementChild) return;

        const marker = 'data-tvu-gen="' + generation + '"';
        if (root.querySelectorAll('[' + marker + ']').length === state.bands.length) return;

        const observer = state.observer;
        if (observer) observer.disconnect();

        const template = root.firstElementChild;
        const thumb = root.lastElementChild;
        Array.from(root.querySelectorAll('[data-tvu-gen]')).forEach(node => node.remove());

        for (const band of state.bands) {
          const span = template.cloneNode(true);
          if (span.removeAttribute) span.removeAttribute('data-test-selector');
          span.setAttribute('data-tvu-gen', String(generation));
          span.style.insetInlineStart = band.left + '%';
          // Twitch has used both logical and physical offsets; set both so the
          // band cannot collapse back to 0% on builds that still emit `left`.
          span.style.left = band.left + '%';
          span.style.right = 'auto';
          span.style.width = band.width + '%';
          span.style.height = '100%';
          span.style.opacity = '1';
          span.style.pointerEvents = 'none';
          span.style.boxShadow = 'inset 0 0 0 1px rgba(0, 0, 0, 0.55)';

          let colour = state.colours.quality;
          if (band.quality === null) colour = state.colours.muted;
          else if (band.quality === state.quality) colour = state.colours.unmuted;
          colour = colour || 'transparent';
          span.style.backgroundColor = colour;

          // Current Twitch markup nests a styled <span> inside .seekbar-segment.
          // That inner span carries its own inset/width/background; without
          // neutralising it, it paints over the band and the highlight is barely
          // visible. Make it fill its parent and use the same colour.
          for (const child of span.querySelectorAll('[style]')) {
            if (child.removeAttribute) child.removeAttribute('data-test-selector');
            child.style.insetInlineStart = '0%';
            child.style.left = '0%';
            child.style.right = 'auto';
            child.style.width = '100%';
            child.style.height = '100%';
            child.style.opacity = '1';
            child.style.backgroundColor = colour;
            child.style.boxShadow = 'none';
          }

          root.insertBefore(span, thumb);
        }

        if (observer) {
          observer.observe(document.documentElement || document.body, {
            childList: true,
            subtree: true
          });
        }
      };

      state.draw = draw;
      draw();

      if (!state.observer) {
        state.observer = new MutationObserver(() => {
          if (state.scheduled) return;
          state.scheduled = true;
          requestAnimationFrame(() => {
            state.scheduled = false;
            if (state.draw) state.draw();
          });
        });
        state.observer.observe(document.documentElement || document.body, {
          childList: true,
          subtree: true
        });
      }
    }

    async function inject(tabId, func, args) {
      if (tabId < 0) return undefined;
      try {
        const results = await api.scripting.executeScript({
          target: { tabId },
          func,
          args: args || [],
          world: 'MAIN'
        });
        return results && results[0] ? results[0].result : undefined;
      } catch (error) {
        console.warn('[tvu] page injection failed', error && error.message);
        return undefined;
      }
    }

    async function readPage(tabId, url) {
      internalUrls.add(url);
      try {
        const page = await inject(tabId, pageFetch, [url]);
        return page || null;
      } finally {
        internalUrls.delete(url);
      }
    }

    async function fetchPlaylist(tabId, url, signal) {
      assertActive(signal);
      const page = await readPage(tabId, url);
      if (page && page.text) return page;
      assertActive(signal);

      // Fallback for cases where injection is unavailable (e.g. tab navigating).
      try {
        const response = await fetch(url);
        if (response.ok) {
          return { ok: true, status: response.status, text: await response.text() };
        }
        return { ok: false, status: response.status, text: '' };
      } catch (error) {
        return { ok: false, status: 0, text: '', error: String(error && error.message || error) };
      }
    }

    /* ---------------------------------------------------------------- */
    /* Network observation                                               */
    /* ---------------------------------------------------------------- */

    if (useBlocking) {
      api.webRequest.onBeforeRequest.addListener(
        async (details) => {
          if (details.tabId < 0) return {};
          if (internalUrls.has(details.url) || probeUrls.has(details.url)) return {};

          const key = segmentKey(details.url);
          const redirects = await getRedirects();
          const target = redirects[key];
          if (target) return { redirectUrl: target };

          // Only a VOD that is actively being scanned may hold a request. Live
          // playlists can also contain `N-muted.ts` names; for those there is no
          // active scan and the request must pass through immediately.
          if (isMutedSegmentUrl(details.url)) {
            const scan = activeScanFor(details.tabId, details.url);
            if (!scan || scan.controller.signal.aborted) return {};
            scan.diagnostics.waitedSegments++;
            await waitForSegment(key);
            const updated = await getRedirects();
            const newTarget = updated[key];
            return newTarget ? { redirectUrl: newTarget } : {};
          }

          return {};
        },
        {
          urls: [
            'https://*.cloudfront.net/*',
            'https://*.ttvnw.net/*',
            'https://*.akamaized.net/*',
            'https://*.twitch.tv/*'
          ],
          types: ['xmlhttprequest', 'media', 'other']
        },
        ['blocking']
      );
    }

    // Learn the quality ladder (and codecs) from the master playlist so that a
    // lower quality is only used when it is codec-compatible with the current one.
    api.webRequest.onCompleted.addListener(
      async (details) => {
        if (details.tabId < 0) return;
        if (!Core.isVodUrl(details.url)) return;
        const identity = scanKey(details.tabId, details.url);
        if (isRecent(seenMasterPlaylists, identity)) return;
        noteSeen(seenMasterPlaylists, identity);

        const page = await readPage(details.tabId, details.url);
        if (!page || !page.text) return;

        const parsed = Core.parseMasterPlaylist(page.text);
        if (!parsed.qualities.length) return;

        await sessionSet('quality:' + details.tabId, {
          qualities: parsed.qualities,
          codecMap: parsed.codecMap,
          at: Date.now()
        });
      },
      { urls: ['https://usher.ttvnw.net/vod/*'], types: ['xmlhttprequest'] }
    );

    const queue = [];
    let processing = false;

    api.webRequest.onCompleted.addListener(
      async (details) => {
        if (details.tabId < 0) return;
        if (!Core.isMutedPlaylistUrl(details.url)) return;

        // Live and VOD both use `index-muted-*.m3u8`, so a positive VOD signal
        // is required: the VOD CDN host, the legacy `/vod/<id>/` path, or a VOD
        // page in this tab. Real VOD playlists live on vod-secure.twitch.tv
        // with a hashed directory and no `/vod/` path at all.
        const pageUrl = await getPageUrl(details.tabId);
        if (!Core.isVodMutedPlaylistUrl(details.url, pageUrl)) {
          await recordDiagnostics(details.tabId, {
            mode: pageUrl && Core.isLivePageUrl(pageUrl) ? 'live' : 'unknown',
            reason: 'playlist outside VOD context',
            url: details.url,
            pageUrl: pageUrl || undefined
          });
          return;
        }

        // Tokens change between player requests. Dedupe on origin + path so one
        // VOD/quality is scanned once instead of queueing duplicate full scans.
        const identity = scanKey(details.tabId, details.url);
        if (isRecent(seenMutedPlaylists, identity)) return;
        noteSeen(seenMutedPlaylists, identity);

        const token = beginScan(details.tabId, details.url);
        if (!token) return;
        queue.push({ tabId: details.tabId, url: details.url, token });
        if (!processing) processQueue();
      },
      {
        urls: [
          'https://*.cloudfront.net/*',
          'https://*.ttvnw.net/*',
          'https://*.akamaized.net/*',
          'https://*.twitch.tv/*'
        ],
        types: ['xmlhttprequest', 'media', 'other']
      }
    );

    /* ---------------------------------------------------------------- */
    /* Playlist processing                                               */
    /* ---------------------------------------------------------------- */

    async function probe(tabId, url, token) {
      const signal = token.controller.signal;
      assertActive(signal);

      const cache = await sessionGet('probes', {});
      const hit = cache[url];
      if (hit && Date.now() - hit.at < PROBE_TTL_MS) return hit.result;
      // A stale failure must not keep a segment muted for the rest of the session.
      delete cache[url];

      probeUrls.add(url);
      token.probeKeys.add(url);
      let tabProbeKeys = probeKeysByTab.get(tabId);
      if (!tabProbeKeys) {
        tabProbeKeys = new Set();
        probeKeysByTab.set(tabId, tabProbeKeys);
      }
      tabProbeKeys.add(url);
      let result;
      try {
        result = (await inject(tabId, pageProbe, [url])) || { errors: PROBE_ATTEMPTS };
      } finally {
        probeUrls.delete(url);
      }
      assertActive(signal);

      // Only remember positive results. A transient network error should be
      // retried on the next scan instead of being cached as "purged".
      if (Core.isAvailable(result.status)) {
        cache[url] = { at: Date.now(), result };
        const keys = Object.keys(cache);
        if (keys.length > PROBE_CACHE_LIMIT) {
          for (const key of keys.slice(0, keys.length - PROBE_CACHE_LIMIT)) delete cache[key];
        }
      }
      await sessionSet('probes', cache);
      return result;
    }

    async function rememberTabUrls(tabId, keys) {
      const map = await sessionGet('tabUrls', {});
      map[tabId] = Array.from(new Set((map[tabId] || []).concat(keys)));
      await sessionSet('tabUrls', map);
    }

    async function processPlaylist(item) {
      const { tabId, url, token } = item;
      const signal = token.controller.signal;
      const diag = token.diagnostics;
      const startedAt = Date.now();

      await recordDiagnostics(tabId, {
        mode: 'vod',
        reason: 'scanning VOD playlist',
        playlist: url,
        dvrStatus: 'pending',
        dvrRequests: 0,
        dvrNames: 0,
        requests: 0,
        failedProbes: 0,
        waitedSegments: 0
      });

      const settings = await getSettings();
      assertActive(signal);
      if (!settings.enabled) return;

      const page = await fetchPlaylist(tabId, url, signal);
      assertActive(signal);
      if (!page || !page.text) return;

      const parsed = Core.parseMutedPlaylist(page.text);
      if (!parsed.segments.length) return;

      // Twitch's unmuted sibling playlist lists the exact filenames that are still
      // available (for example "12-unmuted.mp4"). Try the tokenless URL first,
      // then the player's token URL, so a CDN that requires the token is covered.
      const unmutedNames = {};
      const dvrUrls = [Core.dvrPlaylistUrl(url)];
      const dvrWithToken = Core.dvrPlaylistUrl(url, true);
      if (dvrWithToken !== dvrUrls[0]) dvrUrls.push(dvrWithToken);
      const triedDvr = new Set();
      let dvrHasNames = false;
      let lastDvrStatus = 'failed';

      for (const dvrUrl of dvrUrls) {
        assertActive(signal);
        if (triedDvr.has(dvrUrl)) continue;
        triedDvr.add(dvrUrl);
        diag.dvrRequests++;

        const fetched = await fetchPlaylist(tabId, dvrUrl, signal);
        assertActive(signal);
        if (fetched && fetched.text) {
          const names = Core.parseUnmutedPlaylist(fetched.text);
          const count = Object.keys(names).length;
          if (count) {
            Object.assign(unmutedNames, names);
            diag.dvrNames += count;
            dvrHasNames = true;
            lastDvrStatus = 'ok';
          } else {
            lastDvrStatus = 'empty';
          }
        } else {
          lastDvrStatus = String((fetched && fetched.status) || 'failed');
        }
      }
      diag.dvrStatus = dvrHasNames ? 'ok' : lastDvrStatus;

      const currentQuality = pathnameOf(url).split('/').filter(Boolean).slice(-2)[0] || '';

      const qualityData = await sessionGet('quality:' + tabId, null);
      const qualityFresh = qualityData && qualityData.at &&
        Date.now() - qualityData.at < QUALITY_TTL_MS;
      const qualities = qualityFresh && qualityData.qualities && qualityData.qualities.length
        ? qualityData.qualities
        : Core.DEFAULT_QUALITIES;
      const codecMap = qualityFresh && qualityData.codecMap ? qualityData.codecMap : {};
      const candidates = Core.qualitiesToTry(qualities, codecMap, currentQuality, settings.quality);

      const redirects = await getRedirects();
      const results = [];
      const touchedKeys = [];
      let restored = 0;
      let lowerQuality = 0;
      let dvrRestored = 0;
      let cursor = 0;
      let scanProbes = 0;

      function noteOutcome(outcome) {
        const errors = outcome.errors || 0;
        diag.failedProbes += errors;
        diag.requests += errors + 1;
      }

      async function worker() {
        while (cursor < parsed.segments.length) {
          assertActive(signal);
          const segment = parsed.segments[cursor++];
          let found = null;
          let segmentProbes = 0;
          const exactName = unmutedNames[String(segment.number)];

          async function tryName(quality, name) {
            if (segmentProbes >= MAX_PROBES_PER_SEGMENT ||
                scanProbes >= MAX_PROBES_PER_SCAN) return null;
            const target = Core.buildUnmutedUrl(url, segment.name, quality, name);
            const outcome = await probe(tabId, target, token);
            segmentProbes++;
            scanProbes++;
            noteOutcome(outcome);
            return Core.isAvailable(outcome.status) ? { quality, target } : null;
          }

          // Exact names from index-dvr are far more reliable than guessing.
          // Exhaust them across qualities before sending any plain-name probes.
          if (exactName) {
            for (const quality of candidates) {
              assertActive(signal);
              const hit = await tryName(quality, exactName);
              if (hit) {
                found = Object.assign({ fromDvr: true }, hit);
                break;
              }
            }
          }

          if (!found) {
            const fallbackNames = Core.unmutedNameCandidates(segment.name)
              .filter(name => name !== exactName);
            for (const quality of candidates) {
              for (const name of fallbackNames) {
                assertActive(signal);
                const hit = await tryName(quality, name);
                if (hit) {
                  found = Object.assign({ fromDvr: false }, hit);
                  break;
                }
              }
              if (found) break;
            }
          }

          const mutedUrl = url.replace(/[^/]*$/, segment.name);
          const key = segmentKey(mutedUrl);
          touchedKeys.push(key);

          if (found) {
            assertActive(signal);
            redirects[key] = found.target;
            restored++;
            if (found.quality !== currentQuality) lowerQuality++;
            if (found.fromDvr) dvrRestored++;
            await emitRedirect(key, found.target, tabId);
            // A navigation/timeout that races with DNR rule creation must not
            // leave a rule behind after the tab has been cleaned up.
            if (signal.aborted) await removeTabRules(tabId);
          }
          results.push({ number: segment.number, quality: found ? found.quality : null });

          // Release the player's request for this specific segment as soon as it
          // has been checked. `redirects` is the live in-memory cache, so a waiter
          // that resumes here immediately sees the new mapping.
          markSegmentChecked(key);
        }
      }

      const workers = Math.min(PROBE_CONCURRENCY, parsed.segments.length);
      await Promise.all(Array.from({ length: workers }, worker));
      assertActive(signal);

      await putRedirects(redirects);
      await rememberTabUrls(tabId, touchedKeys);

      const stats = {
        tabId,
        mode: 'vod',
        quality: currentQuality,
        total: parsed.segments.length,
        restored,
        lowerQuality,
        dvrRestored,
        dvrStatus: diag.dvrStatus,
        dvrNames: diag.dvrNames,
        dvrRequests: diag.dvrRequests,
        failedProbes: diag.failedProbes,
        requests: diag.requests,
        waitedSegments: diag.waitedSegments,
        durationMs: Date.now() - startedAt,
        activeScan: false,
        at: Date.now()
      };
      const allStats = await sessionGet('stats', {});
      allStats[tabId] = stats;
      await sessionSet('stats', allStats);
      await recordDiagnostics(tabId, {
        mode: 'vod',
        reason: 'scan finished',
        dvrStatus: diag.dvrStatus,
        dvrNames: diag.dvrNames,
        dvrRequests: diag.dvrRequests,
        requests: diag.requests,
        waitedSegments: diag.waitedSegments,
        durationMs: stats.durationMs
      });
      console.log('[tvu]', tabId, restored + '/' + parsed.segments.length + ' segments restored');

      if (settings.seekbar && results.length) {
        assertActive(signal);
        const bands = Core.buildSeekbarBands(results, parsed.lastNumber);
        await inject(tabId, paintSeekbar, [bands, {
          unmuted: Core.withOpacity(settings.unmutedColour, settings.opacity),
          quality: Core.withOpacity(settings.qualityColour, settings.opacity),
          muted: Core.withOpacity(settings.mutedColour, settings.opacity)
        }, currentQuality]);
      }
    }

    async function processQueue() {
      if (processing) return;
      processing = true;
      while (queue.length) {
        const item = queue.shift();
        try {
          await processPlaylist(item);
        } catch (error) {
          if (!isCancellation(error)) {
            console.error('[tvu] playlist processing failed', error);
          }
        } finally {
          endScan(item.token);
        }
      }
      processing = false;
    }

    /* ---------------------------------------------------------------- */
    /* Cleanup and popup messaging                                       */
    /* ---------------------------------------------------------------- */

    async function clearTabState(tabId) {
      cancelTabScans(tabId);

      const redirects = await getRedirects();
      const tabUrls = await sessionGet('tabUrls', {});
      for (const url of tabUrls[tabId] || []) delete redirects[url];
      await putRedirects(redirects);

      delete tabUrls[tabId];
      await sessionSet('tabUrls', tabUrls);

      const stats = await sessionGet('stats', {});
      delete stats[tabId];
      await sessionSet('stats', stats);
      await sessionSet('diagnostics:' + tabId, null);
      await sessionSet('quality:' + tabId, null);

      const probes = await sessionGet('probes', {});
      for (const key of tokenProbeKeys(tabId)) delete probes[key];
      probeKeysByTab.delete(tabId);
      await sessionSet('probes', probes);

      await removeTabRules(tabId);
    }

    function tokenProbeKeys(tabId) {
      const keys = new Set();
      for (const token of activeScans.values()) {
        if (token.tabId === tabId) {
          for (const key of token.probeKeys) keys.add(key);
        }
      }
      // Scans were cancelled above, also include keys recorded before the tab
      // changed so its probes do not linger in the session cache.
      for (const key of probeKeysByTab.get(tabId) || []) keys.add(key);
      return keys;
    }

    api.tabs.onRemoved.addListener(async (tabId) => {
      await clearTabState(tabId);
      await forgetPageUrl(tabId);
    });

    // Navigation classification is diagnostic only: it must never clear VOD
    // state just because the URL is a player popout or a transitional Twitch
    // URL. Only changeInfo.url is used; status-only updates are not navigation.
    if (api.tabs.onUpdated && api.tabs.onUpdated.addListener) {
      api.tabs.onUpdated.addListener(async (tabId, changeInfo) => {
        const url = changeInfo && changeInfo.url;
        if (!url) return;
        // about:blank, chrome:// and extension pages are intermediate states,
        // not a context change. Treating them as one would cancel active scans.
        if (!/^https?:\/\//i.test(url)) return;

        const previousUrl = await getPageUrl(tabId);
        const previousVodId = previousUrl ? Core.vodIdFromUrl(previousUrl) : null;
        const vodId = Core.isVodUrl(url) ? null : Core.vodIdFromUrl(url);
        await setPageUrl(tabId, url);

        if (Core.isVodUrl(url) || vodId) {
          // A different VOD in the same tab must not inherit old redirects.
          if (previousVodId && previousVodId !== vodId) {
            await clearTabState(tabId);
          }
          // Always overwrite a stale "live" diagnostic when a VOD is opened.
          await recordDiagnostics(tabId, {
            mode: 'vod',
            reason: 'VOD page',
            url,
            vodId: vodId || undefined
          });
          return;
        }

        // Any navigation to a non-VOD URL ends the previous VOD context,
        // whether or not a page URL was observed when the scan began.
        await clearTabState(tabId);
        const live = Core.isLivePageUrl(url);
        await recordDiagnostics(tabId, {
          mode: live ? 'live' : 'unknown',
          reason: live ? 'navigated to live stream' : 'navigated outside VOD',
          url
        });
      });
    }

    api.storage.onChanged.addListener(async (changes, area) => {
      if (area === 'sync' && changes.enabled && changes.enabled.newValue === false) {
        cancelAllScans();
        await putRedirects({});
        await sessionSet('stats', {});
        await clearAllRules();
      }
    });

    api.runtime.onMessage.addListener((message) => {
      if (!message || message.type !== 'tvu:stats') return undefined;

      return (async () => {
        if (message.clear) {
          cancelAllScans();
          await putRedirects({});
          await sessionSet('stats', {});
          await sessionSet('tabUrls', {});
          if (message.tabId != null) {
            await sessionSet('diagnostics:' + message.tabId, null);
          }
          await clearAllRules();
          return { stats: null };
        }

        const all = await sessionGet('stats', {});
        let tabId = message.tabId;
        if (tabId == null) {
          const tabs = await api.tabs.query({ active: true, currentWindow: true });
          tabId = tabs[0] && tabs[0].id;
        }
        const diagnostics = tabId == null
          ? null
          : await sessionGet('diagnostics:' + tabId, null);
        const tabUrls = await sessionGet('tabUrls', {});
        return {
          stats: all[tabId] || null,
          diagnostics: diagnostics ? Object.assign({}, diagnostics, {
            tabId,
            activeScan: activeScanCount(tabId),
            redirects: (tabUrls[tabId] || []).length
          }) : null
        };
      })();
    });

    // Covers a VOD that was already open when the extension loaded and Chrome
    // service-worker restarts, where no onUpdated event will fire for it.
    seedPageUrls();

    // Exposed for tests and diagnostics; no page script can reach this object.
    return {
      segmentKey,
      isMutedSegmentUrl,
      markSegmentChecked,
      queue,
      seenMutedPlaylists,
      activeScans,
      cancelTabScans
    };
  }

  return { createBackground };
});
